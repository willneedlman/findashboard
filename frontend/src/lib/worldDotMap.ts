export const WORLD_DOT_PATH = (() => {
  let path = ''
  WORLD_ROWS.forEach((row, r) => {
    for (let c = 0; c < row.length; c++) {
      if (row[c] !== '#') continue
      const x = c * 10 + 5
      const y = r * 10 + 8
      path += `M${x - 2.6},${y} a2.6,2.6 0 1,0 5.2,0 a2.6,2.6 0 1,0 -5.2,0 `
    }
  })
  return path
})()

export const projectWorld = (lat: number, lon: number) => ({
  x: (lon + 180) / 360 * 660,
  y: (90 - lat) / 180 * 250,
})

